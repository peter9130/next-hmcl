package org.jackhuang.hmcl.ui.main;

import javafx.scene.control.ScrollPane;
import javafx.scene.layout.VBox;
import org.jackhuang.hmcl.Metadata;
import org.jackhuang.hmcl.ui.FXUtils;
import org.jackhuang.hmcl.ui.construct.ComponentList;
import org.jackhuang.hmcl.ui.construct.LineButton;
import org.jackhuang.hmcl.ui.construct.SpinnerPane;

import static org.jackhuang.hmcl.util.i18n.I18n.i18n;

/// Displays the maintainer's community contact channel.
public class FeedbackPage extends SpinnerPane {

    /// Builds a feedback page containing only the maintained Telegram channel.
    public FeedbackPage() {
        VBox content = new VBox();
        content.getStyleClass().add("spinner-pane-content");
        ScrollPane scrollPane = new ScrollPane(content);
        scrollPane.setFitToWidth(true);
        FXUtils.smoothScrolling(scrollPane);
        setContent(scrollPane);

        ComponentList groups = new ComponentList();
        var telegram = LineButton.createExternalLinkButton(Metadata.CONTACT_URL);
        telegram.setLargeTitle(true);
        telegram.setLeading(FXUtils.newBuiltinImage("/assets/img/icon.png"));
        telegram.setTitle("Telegram");
        telegram.setSubtitle("t.me/next_hmcl");
        groups.getContent().setAll(telegram);

        content.getChildren().addAll(
                ComponentList.createComponentListTitle(i18n("contact.chat")),
                groups
        );
    }
}
